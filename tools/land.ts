/* ==========================================================================
   Land mask generator: rasterizes Natural Earth land (world-atlas, 50m) into
   run-length rows for the ground-track map. Output is committed; re-run only
   to change the resolution.
   Run: bun run tools/land.ts
   ========================================================================== */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
import { feature } from 'topojson-client';
import type { Topology, GeometryCollection } from 'topojson-specification';

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = resolve(__dirname, '..');

const RES = 4; // cells per degree
const W = 360 * RES;
const H = 180 * RES;

const topo = JSON.parse(
  readFileSync(resolve(root, 'node_modules/world-atlas/land-50m.json'), 'utf-8'),
) as Topology<{ land: GeometryCollection }>;
const land = feature(topo, topo.objects.land);

type Ring = [number, number][];
const rings: Ring[] = [];
for (const f of land.features) {
  const g = f.geometry;
  if (g.type === 'Polygon') rings.push(...(g.coordinates as Ring[]));
  else if (g.type === 'MultiPolygon') for (const p of g.coordinates as Ring[][]) rings.push(...p);
}

// Even-odd scanline fill at each row's center latitude.
const rows: string[] = [];
let spans = 0;
for (let r = 0; r < H; r++) {
  const lat = 90 - (r + 0.5) / RES;
  const xs: number[] = [];
  for (const ring of rings) {
    for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
      const a = ring[i]!;
      const b = ring[j]!;
      if ((a[1] > lat) !== (b[1] > lat)) {
        xs.push(a[0] + ((lat - a[1]) / (b[1] - a[1])) * (b[0] - a[0]));
      }
    }
  }
  xs.sort((p, q) => p - q);
  const out: number[] = [];
  for (let k = 0; k + 1 < xs.length; k += 2) {
    const s = Math.max(0, Math.round((xs[k]! + 180) * RES));
    const e = Math.min(W, Math.round((xs[k + 1]! + 180) * RES));
    if (e > s) out.push(s, e - s);
  }
  spans += out.length / 2;
  rows.push(out.map((n) => n.toString(36)).join(','));
}

const body = `// Generated by tools/land.ts from Natural Earth 1:50m land (public domain, via world-atlas).
// ${H} rows from 90°N to 90°S, ${RES} cells per degree; each row is base-36 "start,length" pairs.
export const LAND_RES = ${RES};
export const LAND = '${rows.join('|')}';
`;
writeFileSync(resolve(root, 'src/js/site/concept/land-data.ts'), body);
console.log(`✓ land mask: ${spans} spans, ${(body.length / 1024).toFixed(1)} KB`);
